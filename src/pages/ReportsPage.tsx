import React from 'react';
import { CheckCircle2, ExternalLink, FileText } from 'lucide-react';
import { DeskShell } from '@/components/DeskShell';
import { useApp } from '@/context/AppContext';
import { api } from '@/lib/api';

export function ReportsPage() {
  const { desk, activeClientId, openWindow, refreshDesk, showToast } = useApp();
  const artifacts = desk?.artifacts.filter((a) => !activeClientId || a.clientId === activeClientId) ?? [];

  return (
    <DeskShell>
      <div className="space-y-5">
        <div>
          <h1 className="flex items-center gap-2 font-display text-2xl font-bold text-white">
            <FileText className="h-6 w-6 text-cyan-400" />
            Reports &amp; Artifact Library
          </h1>
          <p className="text-xs text-slate-400">
            Open any Technical Audit, Keyword Brief, Content Plan, or Final Recommendation inside draggable OS-style windows.
          </p>
        </div>

        <div className="grid grid-cols-1 gap-4 md:grid-cols-2">
          {artifacts.map((art) => (
            <div key={art.id} className="os-panel flex flex-col justify-between rounded-2xl p-5">
              <div>
                <div className="flex flex-wrap items-center justify-between gap-2">
                  <span className="rounded-full border border-cyan-400/35 bg-cyan-500/15 px-2.5 py-0.5 font-mono-tech text-[10px] text-cyan-200">
                    {art.kind}
                  </span>
                  <div className="flex items-center gap-2">
                    {art.provenance.isMock && (
                      <span className="rounded bg-amber-500/15 px-1.5 py-0.5 font-mono-tech text-[9px] text-amber-200">
                        DEMO / MOCK
                      </span>
                    )}
                    <span className="font-mono-tech text-[10px] text-slate-400">
                      {Math.round(art.confidence * 100)}% confidence
                    </span>
                  </div>
                </div>

                <h2 className="mt-3 font-display text-lg font-bold text-white">{art.title}</h2>
                <p className="mt-1 text-xs text-slate-400">
                  Generated by {art.provenance.generatedBy} · {new Date(art.createdAt).toLocaleString()}
                </p>
                <p className="mt-3 line-clamp-3 rounded-xl border border-white/10 bg-slate-950/70 p-3 text-xs text-slate-300">
                  {art.content.replace(/[#>*`]/g, '')}
                </p>
              </div>

              <div className="mt-4 flex flex-wrap items-center justify-between gap-2">
                <button
                  type="button"
                  onClick={() => openWindow({ title: art.title, kind: 'ARTIFACT', entityId: art.id })}
                  className="inline-flex items-center gap-1.5 rounded-xl bg-cyan-400 px-4 py-2 text-xs font-bold text-slate-950 hover:bg-cyan-300"
                >
                  <ExternalLink className="h-3.5 w-3.5" />
                  Open in OS Window
                </button>
                {!art.approved ? (
                  <button
                    type="button"
                    onClick={async () => {
                      await api.approveArtifact(art.id);
                      await refreshDesk();
                      showToast('Artifact approved with audit receipt.');
                    }}
                    className="inline-flex items-center gap-1 rounded-xl border border-emerald-400/40 bg-emerald-500/15 px-3 py-2 text-xs font-semibold text-emerald-200 hover:bg-emerald-500/25"
                  >
                    <CheckCircle2 className="h-3.5 w-3.5" /> Approve
                  </button>
                ) : (
                  <span className="inline-flex items-center gap-1 text-xs font-medium text-emerald-300">
                    <CheckCircle2 className="h-3.5 w-3.5" /> Approved
                  </span>
                )}
              </div>
            </div>
          ))}
        </div>
      </div>
    </DeskShell>
  );
}
